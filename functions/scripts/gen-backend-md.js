#!/usr/bin/env node
/**
 * gen-backend-md.js — rewrite the AUTOGEN block in BACKEND.md from the zod
 * contract registry, so the "contract surface" list can never drift from the
 * schemas. Everything OUTSIDE the marked block (the rich hand-written
 * inventory, the migration notes) is left untouched.
 *
 *   <!-- AUTOGEN:contract-surface -->
 *   ...generated table...
 *   <!-- /AUTOGEN:contract-surface -->
 *
 * Run from functions/:  node scripts/gen-backend-md.js
 */

"use strict";

const fs = require("fs");
const path = require("path");

const { ALL } = require("../contracts");

const MD_PATH = path.join(__dirname, "..", "..", "BACKEND.md");
const START = "<!-- AUTOGEN:contract-surface -->";
const END = "<!-- /AUTOGEN:contract-surface -->";

const byDomain = {};
for (const c of ALL) (byDomain[c.domain] ??= []).push(c);

const lines = [
  START,
  "",
  "<!-- Generated by `npm run contracts:gen` from functions/contracts/*.js — do not edit by hand. -->",
  "",
  `**${ALL.length} callables** validated by \`validated(name, handler)\`. Request payloads are`,
  "parsed against these schemas before the handler runs; bad payloads are rejected",
  'with `HttpsError("invalid-argument", ...)`. Swift types: `contracts/generated/`.',
  "",
];

for (const [domain, list] of Object.entries(byDomain)) {
  lines.push(`### \`${domain}\``, "", "| Callable | Summary |", "|---|---|");
  for (const c of list.sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`| \`${c.name}\` | ${c.summary} |`);
  }
  lines.push("");
}

lines.push(END);
const block = lines.join("\n");

let md = fs.readFileSync(MD_PATH, "utf8");
const startIdx = md.indexOf(START);
const endIdx = md.indexOf(END);

if (startIdx === -1 || endIdx === -1) {
  // First run: append the block before the "## Settled" section if present,
  // else at the end.
  const anchor = md.indexOf("\n## Settled");
  const insertAt = anchor === -1 ? md.length : anchor;
  md = md.slice(0, insertAt) + "\n---\n\n## Contract surface\n\n" + block + "\n\n" + md.slice(insertAt);
} else {
  md = md.slice(0, startIdx) + block + md.slice(endIdx + END.length);
}

fs.writeFileSync(MD_PATH, md);
console.log(`✓ refreshed ${path.relative(process.cwd(), MD_PATH)} AUTOGEN block (${ALL.length} callables)`);
